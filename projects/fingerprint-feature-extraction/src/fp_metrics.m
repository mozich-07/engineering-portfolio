function m = fp_metrics(y,p)
y=logical(y(:));p=logical(p(:));
tn=sum(~y&~p);fp=sum(~y&p);fn=sum(y&~p);tp=sum(y&p);
m=struct('accuracy',mean(y==p),'precision',tp/max(1,tp+fp), ...
    'recall',tp/max(1,tp+fn),'specificity',tn/max(1,tn+fp), ...
    'f1',2*tp/max(1,2*tp+fp+fn),'macroF1',0.5*(2*tp/max(1,2*tp+fp+fn)+2*tn/max(1,2*tn+fp+fn)), ...
    'confusion',[tn fp;fn tp],'n',numel(y));
end
